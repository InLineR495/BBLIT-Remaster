#pragma once
#include <windows.h>

#define BB_VERSION "1.0-beta"

struct bb_config {
    int splash_fill; // extend uniform startup-logo backgrounds into the bars
    int off;        // REMASTER_OFF=1 или off=1 в ini: только прокси ddraw, игра не трогается
    int log_gpa;    // писать в лог каждый GetProcAddress
    int veh;        // логировать исключения (AV и т. п.), обработку не меняет
    int probes;     // M1: пассивные пробы (probe.c)
    int borderless; // M2 I6/C12: окно без рамки на весь монитор, картинка движка по центру
    int pacer_sleep;// M2 T1: сон до дедлайна вместо прокрутки QPC
    int video_guard;// M2 I11: видео-меню паузы применяет только туман
    int render;     // M3: свой рендер снимка (F9 — переключить A/B с оригиналом)
    int msaa;       // M3: число выборок MSAA (до GL_MAX_SAMPLES)
    int vsync;      // M3: wglSwapIntervalEXT в нашем контексте; −1 — не трогать
    int hor_plus;   // M3: Hor+ (сжатие sx в построении + широкий мир в рендере)
    int hor_guard;  // M3: запас отсечения по краям, % (DESIGN guard ≈ 10)
    int hor_logic;  // M5a H1: расширить экранный тест акторов на ширину Hor+
    int no_quad_split; // M5a R2′: выключить разрез квадов движком при Hor+
    int fix_shadow40;  // M5a H2: 41-я тень не вешает игру
    int fog_sharp;  // M5a: растворение в тумане ×(fog_sharp/10) — 25: только последние 10 % дистанции; 10 — как в оригинале
    int interp;     // M4: промежуточные кадры с частотой экрана (интерполяция между тиками)
    int fps;        // M4: частота кадров; 0 — частота экрана
    int alpha_vb;   // M4f: α по времени показа (следующий vblank после свопа), а не по началу рендера кадра
    int gl_profile; // эксперимент: подмена VENDOR/RENDERER для профиля 0x422050 (−1 — как есть)
    int trans_mode; // полупрозрачное без записи глубины + смещение: 0 — выкл, 1 — вершины с α<255, 2 — всё смешиваемое
    int shader;     // M4b: шейдеры и буферы вершин (0 — немедленный режим, как в M3/M4)
    int ps1_blend;  // M4b: смешивание текстур-вариантов по формулам PS1 (только при shader=1)
    int jump_k;     // M4: множитель порога «скачка» вершины (×10; 10 — сдвиг в пространстве камеры > 0,5·R + 500)
    int repair;     // M4: вершинам без пары восстанавливать положение в A по движению объекта (иначе объект — из B)
    int half_rate;  // M4: объекты с анимацией через тик (15 Гц) — шаг растягивается на две пары
    int half_lock;  // M4: захват анимации через тик держится после сдвига фазы (без рывков 6 пар)
    int spin_hide;  // M4: вращение полупрозрачного эффекта (вихрь) — своё, ровное: скорость по движку, фаза своя
    int spin_snap;  // M4: объект, повернувшийся за тик > ~74° (сжатие в середине < 0,8), — шагом, как в оригинале
    int reproj;     // M4e: вершина без положения в A — поза B при камере A (объект не стоит на тик впереди поворота)
    int ghost;      // M4e: грани A, отсечённые в B, дорисовываются до конца тика (край кадра при повороте)
    int quad_cull;  // M5c: квад комнаты отбрасывается, только если отвёрнуты обе половины (0 — как в оригинале)
    int xinput;     // M6: нативный XInput (N1/N2); 0 — DInput-пад оригинала
    int analog;     // M6: аналоговый стик в игре (радиальная мёртвая зона, без снапа к осям)
    int stick_dz;   // M6: радиальная мёртвая зона стика, %
    int stick_full; // M6: отклонение стика, %, с которого полная скорость (бег)
    int jump_buf;   // M6: буфер прыжка, тиков (0 — выкл.)
    int pad_esc;    // M6: Back = Esc (пауза, «назад»), Start = пауза в игре
    int pad_map;    // M6: 1 — раскладка из joyMap игры (config.pc), 0 — фиксированная PS1-раскладка
    int cam_stick;  // M6 K2: правый стик поворачивает камеру
    int cam_speed;  // M6 K2: шаг рыскания за тик при полном отклонении (0x1000 = 360°; триггеры — 0x26)
    int cam_invert; // M6 K2: инверсия правого стика
    int cam_swap;   // M6: LT/RT обменены (поворот в сторону триггера)
    int dpi_aware;  // Windows: процесс DPI-aware (иначе при масштабе > 100 % картинка в пониженном разрешении); 0 — как было
    int hotkeys;    // отладочные клавиши (F9 — свой рендер / оригинал); 0 — выкл.: в игре пользователя F9 приходил от кнопок
    int big_cores;  // главный поток (логика + рендер) — на самых быстрых ядрах (Zen5 у Z2, а не Zen5c); 0 — как решит ОС
    int sneak;      // M6: до этого отклонения стика, % — подкрадывание (○ + направление) из стойки; 0 — выкл.
    int ptrace;     // отладка: журнал игрока по тикам (PT) на столько тиков; [live] ptrace=N, ключ сбрасывается в 0
    int fog;        // M5b: туман движка (альфа) выключен, наш — попиксельно к заднику (только с шейдерами)
    int draw_dist;  // M5b: дальность ×100 (100 — как в оригинале; >100 — детур 0x40cc80 расширяет отсечки движка)
    int fog_start;  // M5b: начало нашего тумана, % дальности (75 — как у движка)
    int room_depth; // M5b P-FT2: комнаты глубже предела порталов (room+0xb5) на столько уровней рисуются (флаг 2)
    int portal_guard; // M5b: запас границ кадра для теста порталов, % (комната выпадала, когда её портал уходил за край)
    int v_guard;    // M5b YG: вертикальный запас отсечения движка, % (полосы в промежуточных кадрах)
    int haze;       // M5b: дымка у земли, % силы (0 — выкл.)
    int haze_depth; // M5b: верх слоя дымки ниже ног игрока, ед. мира
    int haze_thick; // M5b: толщина перехода по высоте, ед.
    int haze_near, haze_far; // M5b: дымка на геометрии нарастает по дальности от near до far
    int haze_max;   // M5b: предел дымки на геометрии, % (силуэты не пропадают)
    int haze_a0, haze_a1; // M5b: фон — дымка от a0 до a1 градусов ниже горизонта (полоса холмов задника остаётся)
    int fade_in;    // M5b: дальние появившиеся объекты проявляются дизерингом (FADE_TICKS тиков)
    int fence;      // M4g: синхронизация контекстов меткой GPU вместо glFinish
    int p23;        // отладка: статистика краёв P23 на каждой паре (до 0,5 мс на кадре 0)
    int vb_guard;   // M4g: vblank не дальше этой доли периода (%) после дедлайна тика рисуется до логики; 0 — как раньше
    int title_logo; // плашки титула (логотип, меню) ближе к камере: глубина ×title_logo/100 (в оригинале логотип протыкает машина времени); 0 или 100 — как было
    int hud_edges;  // M5: элементы HUD в левой/правой трети у верхнего/нижнего края — к краям широкого экрана
    int hud_aspect; // рамка, к краям которой идут счётчики, ×100: 0 — края экрана, 133 — как в оригинале (4:3), 178 — 16:9 (по умолчанию: шире 16:9 HUD не уходит)
    int decals;     // плоские акторы на земле (норы) рисуются как тени — без борьбы с землёй за глубину; 0 — выкл.
    int shadow_act; // тени на акторах (Багз на бочке): второй проход по пикселям акторов, подтяжка к камере — % от обычной; 0 — выкл.
    int sky_dome;   // купол неба, пришитый к камере (L03A: острова, солнце), — задник: рисуется первым; 0 — как мир, как движок
    int push_r;     // M8: радиус «цилиндра» Багза для выталкивания модели из толкаемого камня (0 — выкл.)
    int log_sec;    // секундные строки P* в remaster.log (0 — тихий режим: старт, ошибки, события)
    int actor_dist; // M5-AR: дистанция включения акторов логикой, % от их +0x3e (100 — как в оригинале)
    uint32_t ar_stock_actor, ar_stock_actor2; // отладка M5-AR: акторы с адресом в [от, до] ([live] hex «от-до») — по стоковой дальности
    int ar_stock_type; // отладка M5-AR: акторы этого типа (+0x2c) — по стоковой дальности; −1 — нет
    int dive_gate;  // M5-AR: условие логики «игрок в нырке» (код 0x34) у актора, которого ×4 держит дальше стокового R: 0 — как есть (обе норы L03A срабатывают), 1 — ложно (как в стоке; по умолчанию), 2 — только лог
    int part_extra; // M5-AR: пул частей уровня в своём буфере на столько частей больше (0 — пул движка, как в оригинале)
    int ps1_light;  // яркость мира ×10: тексель × цвет вершины × ps1_light/10 (20 — как PS1, 0x80 — нейтраль; порт — /255, вдвое темнее); 0 — как порт
    int uv_clamp;    // смешиваемое по альфе с uv в [0, 1] — выборка без заворота через край (линии по периметру)
    int uv_centroid; // uv в точке внутри треугольника (MSAA): без пунктира по краям полигонов
    int alpha_split; // смешивание по альфе текстуры с записью глубины — два прохода: прозрачное не заслоняет акторов
    int ps1_stp;    // тексели без бита STP (альфа варианта выше предела режима) в PS1-смешивании непрозрачны; 0 — всё смешивается
    int ps1_gain;   // M4b: яркость F в PS1-смешивании, ×10 (10 — цвет вершины /255, как на ПК; 20 — /128, как на PS1)
    int fix_sfx;    // звук (sfx.c): позиционная петля вне слышимости — 0 сиротеет и играет вечно (оригинал), 1 — стоп и возврат при подходе (виртуальный голос; по умолчанию), 2 — только штатный стоп
};

extern struct bb_config bb_cfg;
extern HINSTANCE bb_self;

void bb_config_load(void);
void bb_config_live(void);   // раз в секунду: [live] render=0/1 (A/B с SSH на лету)
void bb_entry_stub(void);   // детур entry0 0x451eb0 -> bb_late_init -> 0x451eb5
extern uint32_t bb_entry_resume;   // адрес продолжения entry0 в раскладке хоста
void bb_late_init(void);
void bb_probe_init(void);
void bb_window_init(void);
void bb_pacer_init(void);
void bb_menu_guard_init(void);
void bb_edges_init(void);
void bb_probe_exit(void);
uint32_t bb_level_loads(void);       // счётчик загрузок уровня (растёт на каждой LVL #)
void bb_input_init(void);            // M6: XInput, аналог, буфер прыжка, пауза с пада
void bb_input_log_second(void);
void bb_sfx_init(void);              // звук: сайты 0x41da00/0x41edb0/0x41f2e1/0x41f3d4 (sfx.c)
void bb_sfx_log_second(void);        // строка P32 (раз в секунду, probe.c)
void bb_sfx_dump(void);              // [live] snd_dump=1: голоса 0x4b3260 и петли 0x553200 в лог
